"""Learns a human drummer's feel from the Groove MIDI Dataset and writes paleo/engine/groove_feel.h.

Groove MIDI Dataset (Google, CC BY 4.0, https://magenta.tensorflow.org/datasets/groove): 13.6 hours of ten
drummers playing an electronic kit. Only the 4/4 "beat" takes in straight (not swung) styles are used:
rock, funk, afrobeat, afrocuban, latin, highlife, middleeastern, reggae, pop, punk, dance, country, soul.

For every 16th of the bar and three kinds of drum (low: kick; mid: snare and toms; high: hats and ride), it
measures how far real hits land from the grid (in 16ths, mean and spread) and how hard they are (velocity relative
to that drum's average, mean and spread). The conductor's drummer nudges its hits by these amounts.
Usage: groove.py GROOVE_DIR"""
import sys, os, csv, math
import mido
LOW = {35, 36}
MID = {37, 38, 40, 41, 43, 45, 47, 48, 50, 58}
HIGH = {22, 26, 42, 44, 46, 51, 53, 59}
STRAIGHT = {"rock", "funk", "afrobeat", "afrocuban", "latin", "highlife", "middleeastern", "reggae", "pop", "punk",
            "dance", "country", "soul"}
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "engine", "groove_feel.h")

def main(root):
    off = [[[] for _ in range(16)] for _ in range(3)]; vel = [[[] for _ in range(16)] for _ in range(3)]
    takes = 0
    for r in csv.DictReader(open(os.path.join(root, "info.csv"))):
        if r["beat_type"] != "beat" or r["time_signature"] != "4-4": continue
        style = r["style"].split("/")
        if style[0] not in STRAIGHT or any(w in r["style"] for w in ("shuffle", "swing", "halftime")): continue
        m = mido.MidiFile(os.path.join(root, r["midi_filename"])); tpb = m.ticks_per_beat
        t = 0; hits = []
        for msg in mido.merge_tracks(m.tracks):
            t += msg.time
            if msg.type != "note_on" or msg.velocity == 0: continue
            cls = 0 if msg.note in LOW else 1 if msg.note in MID else 2 if msg.note in HIGH else -1
            if cls < 0: continue
            pos = t / tpb * 4                                  # in 16ths from the start
            k = round(pos); d = pos - k
            if abs(d) > .5: continue
            hits.append((cls, k, d, msg.velocity))
        # drift: the drummer speeding up or slowing down against the file's tempo is not feel, so each bar's
        # average offset is taken away
        bars = {}
        for cls, k, d, v in hits: bars.setdefault(k // 16, []).append(d)
        for cls, k, d, v in hits:
            b = bars[k // 16]; d -= sum(b) / len(b)
            off[cls][k % 16].append(d); vel[cls][k % 16].append(v)
        takes += 1
    def ms(xs):
        if len(xs) < 20: return 0.0, 0.0
        mu = sum(xs) / len(xs); return mu, math.sqrt(sum((x - mu) ** 2 for x in xs) / len(xs))
    names = ["low", "mid", "high"]
    with open(OUT, "w") as o:
        o.write("/* SPDX-License-Identifier: GPL-3.0-only */\n/* Generated by paleo/phrases/groove.py: do not edit. A human drummer's feel, from %d straight 4/4 takes\n" % takes)
        o.write("   in the Groove MIDI Dataset (Google, CC BY 4.0). Per drum kind (low, mid, high) and 16th of the bar:\n")
        o.write("   timing off the grid in 16ths (mean, spread) and velocity relative to that drum's average (mean, spread). */\n#pragma once\n")
        for label, idx in (("kFeelOff", 0), ("kFeelOffSd", 1), ("kFeelVel", 2), ("kFeelVelSd", 3)):
            o.write("static const float %s[3][16] = {\n" % label)
            for c in range(3):
                allv = [v for row in vel[c] for v in row]; avg = sum(allv) / max(1, len(allv))
                row = []
                for k in range(16):
                    if idx < 2:
                        mu, sd = ms(off[c][k]); row.append(mu if idx == 0 else sd)
                    else:
                        mu, sd = ms([v / avg for v in vel[c][k]])
                        row.append((mu if idx == 2 else sd) if vel[c][k] and len(vel[c][k]) >= 20 else (1.0 if idx == 2 else 0.0))
                o.write("  {" + ", ".join("%.3ff" % x for x in row) + "},  /* %s */\n" % names[c])
            o.write("};\n")
    print("wrote groove_feel.h from %d takes" % takes)
    for c in range(3):
        print(names[c], "timing", " ".join("%+.2f" % ms(off[c][k])[0] for k in range(16)))
        print(names[c], "spread", " ".join("%.2f" % ms(off[c][k])[1] for k in range(16)))

if __name__ == "__main__":
    main(sys.argv[1])
