"""Packs the phrase files into paleo/engine/phrase_bank.h, which the conductor's Markov melody chains learn from.

Reads every *-travel.txt, *-majesty.txt, *-danger.txt and *-coda.txt under pd/ and written/ (check.py format).
No single file gives more than CAP phrases to a kind (picked evenly through the file), so one big source
cannot drown out the others. Phrases with wild jumps are left out (see smooth()).

Packing, one phrase after another: kind (0 travel, 1 majesty, 2 danger, 3 coda), note count, then for each
note its degree + 16 and the index of its length in kBankBeats. The bank ends with 255.
Usage: bank.py [CAP]"""
import sys, os, glob
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from check import parse
BEATS = [0.25, .5, .75, 1, 1.5, 2, 3, 4, 6]
KINDS = ["travel", "majesty", "danger", "coda"]
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "engine", "phrase_bank.h")

def smooth(p, kind):
    """No wild jumps: no leap over an octave, and at most one leap of a sixth or more (two for majesty)."""
    jumps = [abs(p[i + 1][0] - p[i][0]) for i in range(len(p) - 1)]
    return max(jumps) <= 7 and sum(1 for j in jumps if j >= 5) <= (2 if kind == "majesty" else 1)

def main():
    cap = int(sys.argv[1]) if len(sys.argv) > 1 else 40000
    data = bytearray(); counts = {k: 0 for k in KINDS}; files = []
    for ki, kind in enumerate(KINDS):
        for f in sorted(glob.glob(os.path.join(HERE, "pd", "*-%s.txt" % kind)) + glob.glob(os.path.join(HERE, "written", "*-%s.txt" % kind))):
            ps = [p for p in (parse(l) for l in open(f, encoding="utf-8") if not l.lstrip().startswith("#")) if p and smooth(p, kind)]
            if len(ps) > cap: ps = [ps[int(i * len(ps) / cap)] for i in range(cap)]
            files.append("%s: %d" % (os.path.relpath(f, HERE), len(ps)))
            for p in ps:
                data += bytes([ki, len(p)])
                for d, b in p: data += bytes([d + 16, BEATS.index(b)])
            counts[kind] += len(ps)
    data.append(255)
    with open(OUT, "w") as o:
        o.write("/* SPDX-License-Identifier: GPL-3.0-only */\n")
        o.write("/* Generated by paleo/phrases/bank.py: do not edit. Melody phrases from real music for the conductor's\n")
        o.write("   Markov chains. Sources and credits: paleo/phrases/SOURCES.md.\n")
        for line in files: o.write("     %s\n" % line)
        o.write("   travel %d, majesty %d, danger %d, coda %d phrases. */\n" % tuple(counts[k] for k in KINDS))
        o.write("#pragma once\n#include <cstdint>\n")
        o.write("static const float kBankBeats[9] = {.25f, .5f, .75f, 1, 1.5f, 2, 3, 4, 6};\n")
        o.write("static const uint8_t kPhraseBank[%d] = {\n" % len(data))
        for i in range(0, len(data), 40):
            o.write(",".join(str(x) for x in data[i:i + 40]) + ",\n")
        o.write("};\n")
    print("wrote %s: %d bytes, %s" % (os.path.relpath(OUT, HERE), len(data), counts))

if __name__ == "__main__":
    main()
